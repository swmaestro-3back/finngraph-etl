    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                 TEXT NOT NULL,
    ticker               TEXT NOT NULL,
    market               TEXT NOT NULL,
    company_id           BIGINT REFERENCES companies (id),
    standard_code        TEXT NOT NULL,
