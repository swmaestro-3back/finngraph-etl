END $$;

-- ── companies ───────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS companies (
    id                   BIGSERIAL PRIMARY KEY,
    name                 TEXT NOT NULL,
    ticker               VARCHAR(20),
    corp_code            TEXT,
    is_listed            BOOLEAN NOT NULL,
    description          TEXT,
    description_source   TEXT,
    -- 설명을 만든 원천 공시. 새 보고서가 없으면 설명을 다시 만들지 않는다.
    description_rcept_no TEXT,
    wikidata_qid         TEXT,
    ceo_name             TEXT,
    country              TEXT NOT NULL,
    industry_code        TEXT,
    established_on       DATE,
    fiscal_month         TEXT,
    homepage             TEXT,
    address              TEXT,
    delisted_at          DATE,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS companies_active_ticker_uk
  ON companies (ticker) WHERE delisted_at IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS companies_corp_code_uk
  ON companies (corp_code) WHERE corp_code IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS companies_wikidata_uk
  ON companies (wikidata_qid) WHERE wikidata_qid IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_companies_name ON companies (name);
CREATE INDEX IF NOT EXISTS companies_country_idx ON companies (country);

